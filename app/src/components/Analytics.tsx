import { useEffect, useState } from 'react'
import { api, type AnalyticsData, type Anomaly, type NewTicket, type Ticket } from '../api'
import { compact } from '../format'
import { BarList, LineChart } from './Charts'
import TicketForm from './TicketForm'

const PLATFORMS = ['', 'Instagram', 'TikTok', 'YouTube']
const METRICS = {
  reach: { label: 'Reach', format: (v: number) => compact(v) },
  engagement_rate: { label: 'Engagement rate', format: (v: number) => (100 * v).toFixed(1) + '%' },
  posts: { label: 'Posts', format: (v: number) => String(Math.round(v)) },
} as const
type Metric = keyof typeof METRICS

const SEVERITY = {
  high: { label: 'High', icon: '!' },
  medium: { label: 'Medium', icon: '▲' },
  info: { label: 'Info', icon: 'i' },
}

const pct = (v: number) => (100 * v).toFixed(1) + '%'
const monthLabel = (m: string) => new Date(m + '-01').toLocaleString('en-GB', { month: 'short' })

export default function Analytics({ onTicketCreated }: { onTicketCreated: (t: Ticket) => void }) {
  const [platform, setPlatform] = useState('')
  const [metric, setMetric] = useState<Metric>('reach')
  const [data, setData] = useState<AnalyticsData | null>(null)
  const [showTable, setShowTable] = useState(false)
  const [ticketDraft, setTicketDraft] = useState<Partial<NewTicket> | null>(null)
  const [error, setError] = useState('')

  useEffect(() => {
    api
      .analytics(platform)
      .then((d) => {
        setData(d)
        setError('')
      })
      .catch((e) => setError(e.message))
  }, [platform])

  if (error && !data) return <div className="content empty">Could not load the analytics ({error}). Is the backend running (make api)?</div>
  if (!data) return <div className="content empty">Loading...</div>
  const k = data.kpis
  const m = METRICS[metric]

  function ticketFrom(a: Anomaly) {
    setTicketDraft({ kind: 'task', ...a.ticket })
  }

  return (
    <div className="content analytics">
      <div className="source-banner">
        <b>Synthetic data.</b> {data.source.note} Generated by <code>{data.source.generator}</code> (seed{' '}
        {data.source.seed}), posts from {k.first_post?.slice(0, 10)} to {k.last_post?.slice(0, 10)}. Real metrics would come from
        the Instagram / TikTok / YouTube business APIs.
      </div>

      <div className="toolbar">
        <div className="segmented">
          {PLATFORMS.map((p) => (
            <button key={p} className={platform === p ? 'on' : ''} onClick={() => setPlatform(p)}>
              {p || 'All platforms'}
            </button>
          ))}
        </div>
      </div>

      <div className="kpis">
        <div className="kpi">
          <span>Posts</span>
          <b>{k.posts.toLocaleString('en-US')}</b>
          <small>{k.creators} creators</small>
        </div>
        <div className="kpi">
          <span>Total reach</span>
          <b>{compact(k.reach)}</b>
          <small>{compact(k.impressions)} impressions</small>
        </div>
        <div className="kpi">
          <span>Engagement rate</span>
          <b>{pct(k.engagement_rate)}</b>
          <small>(likes + comments + shares + saves) / reach</small>
        </div>
        <div className="kpi">
          <span>Paid posts</span>
          <b>{k.paid_posts}</b>
          <small className={k.undisclosed_paid ? 'bad' : ''}>
            {k.undisclosed_paid ? `⚠ ${k.undisclosed_paid} without disclosure` : 'all disclosed'}
          </small>
        </div>
      </div>

      <div className="grid-2">
        <div className="card">
          <div className="card-title-row">
            <div>
              <div className="card-title">{m.label} by month of posting</div>
              <div className="muted small-text">{platform || 'All platforms'}</div>
            </div>
            <div className="segmented small">
              {(Object.keys(METRICS) as Metric[]).map((key) => (
                <button key={key} className={metric === key ? 'on' : ''} onClick={() => setMetric(key)}>
                  {METRICS[key].label}
                </button>
              ))}
            </div>
          </div>
          <LineChart points={data.monthly.map((row) => ({ label: monthLabel(row.month), value: row[metric] }))} format={m.format} />
          <button className="link" onClick={() => setShowTable(!showTable)}>
            {showTable ? 'Hide table' : 'Show as table'}
          </button>
          {showTable && (
            <div className="table-wrap">
              <table>
                <thead>
                  <tr>
                    <th>Month</th>
                    <th>Posts</th>
                    <th>Reach</th>
                    <th>Engagement rate</th>
                  </tr>
                </thead>
                <tbody>
                  {data.monthly.map((row) => (
                    <tr key={row.month}>
                      <td>{row.month}</td>
                      <td className="num">{row.posts}</td>
                      <td className="num">{row.reach.toLocaleString('en-US')}</td>
                      <td className="num">{pct(row.engagement_rate)}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}
        </div>

        <div className="card">
          <div className="card-title">Engagement rate by format</div>
          <div className="muted small-text" style={{ marginBottom: 12 }}>
            Compare formats with each other, not with an absolute target (reporting SOP 3.1).
          </div>
          <BarList
            items={data.formats.map((f) => ({ label: f.format, value: f.engagement_rate, detail: `${f.posts} posts, avg reach ${compact(f.avg_reach)}` }))}
            format={pct}
          />
        </div>
      </div>

      <div className="card">
        <div className="card-title">
          Things to check <span className="muted">{data.anomalies.length}</span>
        </div>
        <div className="muted small-text" style={{ marginBottom: 10 }}>
          Found automatically with simple rules: paid posts without disclosure, likes rising much more than reach
          (possible fake likes), posts with 5x the usual reach, and month-to-month reach drops of more than 25%.
        </div>
        {data.anomalies.length === 0 && <div className="empty small">Nothing to check for this platform.</div>}
        {data.anomalies.map((a, i) => (
          <div key={i} className={`anomaly sev-${a.severity}`}>
            <span className="sev-icon" aria-hidden="true">
              {SEVERITY[a.severity].icon}
            </span>
            <span className="sev-label">{SEVERITY[a.severity].label}</span>
            <span className="anomaly-text">{a.text}</span>
            <button className="btn ghost small" onClick={() => ticketFrom(a)}>
              Create ticket
            </button>
          </div>
        ))}
      </div>

      <div className="card">
        <div className="card-title">Creators</div>
        <div className="table-wrap">
          <table>
            <thead>
              <tr>
                <th>Creator</th>
                <th>Niche</th>
                <th>Country</th>
                <th className="num">Instagram</th>
                <th className="num">TikTok</th>
                <th className="num">YouTube</th>
                <th className="num">Posts</th>
                <th className="num">Reach</th>
                <th>Engagement rate</th>
              </tr>
            </thead>
            <tbody>
              {data.creators.map((c) => {
                const best = Math.max(...data.creators.map((x) => x.engagement_rate))
                return (
                  <tr key={c.creator_id}>
                    <td>
                      <b>{c.name}</b>
                    </td>
                    <td>{c.niche}</td>
                    <td>{c.country}</td>
                    <td className="num">{c.followers.Instagram ? compact(c.followers.Instagram) : '-'}</td>
                    <td className="num">{c.followers.TikTok ? compact(c.followers.TikTok) : '-'}</td>
                    <td className="num">{c.followers.YouTube ? compact(c.followers.YouTube) : '-'}</td>
                    <td className="num">{c.posts}</td>
                    <td className="num">{compact(c.reach)}</td>
                    <td>
                      <div className="inline-bar">
                        <div className="inline-track">
                          <div style={{ width: `${(c.engagement_rate / best) * 100}%` }} />
                        </div>
                        <span>{pct(c.engagement_rate)}</span>
                      </div>
                    </td>
                  </tr>
                )
              })}
            </tbody>
          </table>
        </div>
        <div className="muted small-text" style={{ marginTop: 8 }}>
          Followers = current audience per platform (all platforms, not filtered).
        </div>
      </div>

      {ticketDraft && (
        <TicketForm
          initial={ticketDraft}
          onClose={() => setTicketDraft(null)}
          onCreated={(t) => {
            setTicketDraft(null)
            onTicketCreated(t)
          }}
        />
      )}
    </div>
  )
}
